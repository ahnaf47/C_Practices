#include<stdio.h>
int main (){

    int a,b;

    a=18;
    b=65;


    printf("Addition:\n");
    printf("%d + %d = %d.\n",a,b,a+b);

    printf("Subtraction:\n");
    printf("%d - %d = %d.\n",a,b,a-b);

    printf("Multipication:\n");
    printf("%d * %d = %d.\n",a,b,a*b);

    printf("Division:\n");
    printf("%d / %d = %f.\n",a,b,(a*1.0)/b);



    return 0;
}

